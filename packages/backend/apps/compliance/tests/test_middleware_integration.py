"""Security middleware end-to-end integration tests.

Verifies the full request flow through the middleware chain:
RequestIdMiddleware -> AuditMiddleware -> SecurityPolicyMiddleware

Tests cover request ID propagation, audit logging for security-rejected
requests, middleware ordering behaviour, and combined middleware effects.
"""

