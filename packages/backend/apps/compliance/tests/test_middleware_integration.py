class TestUnauthenticatedRequests:
    def test_anonymous_passes_security_middleware(self, rf):
        """Anonymous users bypass security policy enforcement."""
        from django.contrib.auth.models import AnonymousUser

        chain = _build_chain()
        request = rf.get("/api/v1/spaces/")
        request.user = AnonymousUser()
        session = SessionStore()
        session.create()
        request.session = session
        request.META["REMOTE_ADDR"] = "127.0.0.1"
        request.META["HTTP_USER_AGENT"] = "TestAgent/1.0"

        response = chain(request)
        assert response.status_code == 200

    def test_anonymous_mutating_request_still_audited(self, rf):
        """An anonymous POST to /api/ is still audit-logged."""
        from django.contrib.auth.models import AnonymousUser

        chain = _build_chain()
        request = rf.post("/api/v1/auth/register")
        request.user = AnonymousUser()
        session = SessionStore()
        session.create()
        request.session = session
        request.META["REMOTE_ADDR"] = "5.5.5.5"
        request.META["HTTP_USER_AGENT"] = "TestAgent/1.0"
        request.request_id = (
            "anon-audit"  # RequestIdMiddleware will overwrite, but set for tracing
        )

        chain(request)

        # The RequestIdMiddleware generates its own ID, so look for any audit entry for this path
        entries = AuditLog.objects.filter(
            actor_id=None, metadata__path="/api/v1/auth/register"
        )
        assert entries.exists()
