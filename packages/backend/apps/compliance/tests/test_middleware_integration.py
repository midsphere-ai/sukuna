from apps.compliance.security_middleware import SecurityPolicyMiddleware
from apps.users.tests.factories import UserFactory
from apps.workspace.models import Organization, OrganizationMembership, OrganizationRole
from config.middleware.request_id import RequestIdMiddleware

pytestmark = pytest.mark.django_db


@pytest.fixture(autouse=True)
def _clear_cache():
    cache.clear()
    yield
    cache.clear()


@pytest.fixture
def rf():
    return RequestFactory()


@pytest.fixture
def user():
    return UserFactory()


def _build_chain(final_response=None):
    """Build the middleware chain: RequestId -> Audit -> Security -> view.

    Returns the outermost middleware (RequestIdMiddleware).
    """
    resp = final_response or HttpResponse(status=200, content=b"ok")

    def view(request):
        return resp

    security_mw = SecurityPolicyMiddleware(view)
    audit_mw = AuditMiddleware(security_mw)
    request_id_mw = RequestIdMiddleware(audit_mw)
    return request_id_mw


def _make_authenticated_request(
    rf, user, path="/api/v1/spaces/", method="get", last_activity=None, **meta
):
    """Build a fully prepared request for the middleware chain."""
    factory_method = getattr(rf, method)
    request = factory_method(path, **{f"HTTP_{k.upper()}": v for k, v in meta.items()})
    request.user = user

    session = SessionStore()
    if last_activity is not None:
        session["_last_activity"] = last_activity
    else:
        session["_last_activity"] = time.time()
    session.create()
    request.session = session
    request.META.setdefault("REMOTE_ADDR", "127.0.0.1")
    request.META.setdefault("HTTP_USER_AGENT", "TestAgent/1.0")
    return request


# ============================================================================
# Request ID propagation through the chain
# ============================================================================


class TestRequestIdPropagation:
    def test_generated_request_id_in_response_header(self, rf, user):
        """RequestIdMiddleware sets X-Request-Id on the response."""
        chain = _build_chain()
        request = _make_authenticated_request(rf, user)
        response = chain(request)
        assert "X-Request-Id" in response
        assert len(response["X-Request-Id"]) == 32  # UUID hex

    def test_upstream_request_id_preserved(self, rf, user):
        """If X-Request-Id header is sent, it's preserved (not replaced)."""
        chain = _build_chain()
        request = _make_authenticated_request(rf, user, x_request_id="upstream-req-123")
        response = chain(request)
        assert response["X-Request-Id"] == "upstream-req-123"

    def test_request_id_attached_to_request_object(self, rf, user):
        """request.request_id is set by RequestIdMiddleware for downstream use."""
        captured = {}

        def capturing_view(request):
            captured["request_id"] = getattr(request, "request_id", None)
            return HttpResponse(status=200)

        mw = RequestIdMiddleware(capturing_view)
        request = rf.get("/api/v1/test")
        request.user = user
        mw(request)
        assert captured["request_id"] is not None

    def test_request_id_flows_into_audit_log(self, rf, user):
        """The request_id generated by RequestIdMiddleware appears in AuditLog entries."""
        chain = _build_chain()
        request = _make_authenticated_request(
            rf,
            user,
            path="/api/v1/test/resource",
            method="post",
            x_request_id="trace-abc",
        )
        chain(request)

        entry = AuditLog.objects.filter(request_id="trace-abc").first()
        assert entry is not None
        assert entry.metadata["method"] == "POST"


