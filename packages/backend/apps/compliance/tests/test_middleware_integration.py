class TestAuditOnSecurityRejection:
    def test_mfa_blocked_request_still_audited(self, rf, user):
        """A POST request blocked by MFA enforcement is still logged by AuditMiddleware."""
        org = Organization.objects.create(name="MFA Corp", mfa_required=True)
        OrganizationMembership.objects.create(
            organization=org, user=user, role=OrganizationRole.MEMBER
        )

        chain = _build_chain()
        with patch("allauth.mfa.utils.is_mfa_enabled", return_value=False):
            request = _make_authenticated_request(
                rf,
                user,
                path="/api/v1/chat/completions/start",
                method="post",
                x_request_id="mfa-block-test",
            )
            chain(request)

        # AuditMiddleware runs after SecurityPolicyMiddleware, but the 403 response
        # is set by SecurityPolicyMiddleware.process_request which short-circuits.
        # AuditMiddleware's process_response should still fire with the 403 response.
        entry = AuditLog.objects.filter(request_id="mfa-block-test").first()
        assert entry is not None
        assert entry.metadata["status_code"] == 403

    def test_session_expired_request_audited(self, rf, user):
        """A POST request rejected due to session timeout is still logged."""
        org = Organization.objects.create(
            name="Timeout Corp", session_timeout_minutes=10
        )
        OrganizationMembership.objects.create(
            organization=org, user=user, role=OrganizationRole.MEMBER
        )

        chain = _build_chain()
        expired = time.time() - (11 * 60)
        request = _make_authenticated_request(
            rf,
            user,
            path="/api/v1/spaces/create",
            method="post",
            last_activity=expired,
            x_request_id="timeout-audit-test",
        )
        chain(request)

        entry = AuditLog.objects.filter(request_id="timeout-audit-test").first()
        assert entry is not None
        assert entry.metadata["status_code"] == 401


