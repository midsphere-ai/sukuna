class TestSessionTrackingThroughChain:
    def test_session_created_on_authenticated_request(self, rf, user):
        """An authenticated request through the full chain creates a UserSession record."""
        chain = _build_chain()
        request = _make_authenticated_request(rf, user)
        chain(request)

        assert UserSession.objects.filter(user=user).exists()

    def test_session_eviction_through_chain(self, rf, user):
        """Concurrent session limits are enforced through the full middleware chain."""
        org = Organization.objects.create(name="Session Org", max_concurrent_sessions=2)
        OrganizationMembership.objects.create(
            organization=org, user=user, role=OrganizationRole.MEMBER
        )

        chain = _build_chain()
        session_keys = []
        for _ in range(3):
            request = _make_authenticated_request(rf, user)
            chain(request)
            session_keys.append(request.session.session_key)

        assert UserSession.objects.filter(user=user).count() == 2
        remaining_keys = set(
            UserSession.objects.filter(user=user).values_list("session_key", flat=True)
        )
        assert session_keys[0] not in remaining_keys


