class TestCombinedMiddleware:
    def test_successful_request_through_full_chain(self, rf, user):
        """A normal request passes through all middleware without issues."""
        chain = _build_chain(final_response=HttpResponse(status=201))
        request = _make_authenticated_request(
            rf,
            user,
            path="/api/v1/spaces/",
            method="post",
            x_request_id="full-chain-ok",
        )
        response = chain(request)
        assert response.status_code == 201
        assert response["X-Request-Id"] == "full-chain-ok"

        entry = AuditLog.objects.filter(request_id="full-chain-ok").first()
        assert entry is not None
        assert entry.metadata["status_code"] == 201

    def test_get_request_not_audited_but_passes_security(self, rf, user):
        """GET requests pass security checks but are not audit-logged (read-only)."""
        chain = _build_chain()
        request = _make_authenticated_request(
            rf, user, path="/api/v1/spaces/", method="get", x_request_id="get-no-audit"
        )
        response = chain(request)
        assert response.status_code == 200

        entry = AuditLog.objects.filter(
            request_id="get-no-audit", metadata__has_key="method"
        ).first()
        assert entry is None

    def test_security_policy_does_not_break_audit(self, rf, user):
        """Even if SecurityPolicyMiddleware errors internally, audit still works."""
        chain = _build_chain()
        request = _make_authenticated_request(
            rf, user, path="/api/v1/test/", method="post", x_request_id="security-err"
        )

        # Patch _enforce to raise — middleware should swallow it
        with patch.object(
            SecurityPolicyMiddleware, "_enforce", side_effect=RuntimeError("boom")
        ):
            response = chain(request)

        assert response.status_code == 200
        entry = AuditLog.objects.filter(
            request_id="security-err", metadata__has_key="method"
        ).first()
        assert entry is not None


