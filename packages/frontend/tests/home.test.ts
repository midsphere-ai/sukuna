import { expect, test, type Page } from '@playwright/test';

const MOCK_USER = {
	id: 'usr_test123',
	name: 'Test User',
	email: 'test@example.com',
	is_active: true,
	date_joined: '2026-01-01T00:00:00Z',
	last_login: '2026-02-24T00:00:00Z'
};

const MOCK_TOKEN = 'test-auth-token-abc123';

async function mockCommonRoutes(page: Page): Promise<void> {
	// Catch-all fallback for unmatched API requests (registered first = lowest priority in LIFO)
	// Only intercept fetch/xhr — let page navigations (document) through
	await page.route('**/*', async (route) => {
		const type = route.request().resourceType();
		if (type !== 'fetch' && type !== 'xhr') return route.continue();
		const url = route.request().url();
		if (
			url.includes('/workspace/') ||
			url.includes('/memory/') ||
			url.includes('/cms/') ||
			url.includes('/chat/') ||
			url.includes('/billing/') ||
			url.includes('/authentication/')
		) {
			return route.fulfill({ status: 200, contentType: 'application/json', body: '{}' });
		}
		return route.continue();
	});

	await page.route('**/cms/public/**', (route) =>
		route.fulfill({ status: 200, contentType: 'application/json', body: '{}' })
	);
	await page.route('**/cms/home-banner', (route) =>
		route.fulfill({ status: 200, contentType: 'application/json', body: '{}' })
	);
	await page.route('**/cms/public/tutorials', (route) =>
		route.fulfill({
			status: 200,
			contentType: 'application/json',
			body: JSON.stringify({ items: [], count: 0 })
		})
	);
	await page.route('**/memory/addons**', (route) =>
		route.fulfill({
			status: 200,
			contentType: 'application/json',
			body: JSON.stringify({ items: [], count: 0 })
		})
	);
	await page.route('**/memory/mcp-configs**', (route) =>
		route.fulfill({
			status: 200,
			contentType: 'application/json',
			body: JSON.stringify({ items: [], count: 0 })
		})
	);
	await page.route('**/memory/conversations/stream/**', (route) =>
		route.fulfill({ status: 200, contentType: 'text/event-stream', body: '' })
	);
	await page.route('**/memory/conversations?**', (route) =>
		route.fulfill({
			status: 200,
			contentType: 'application/json',
			body: JSON.stringify({ items: [], count: 0 })
		})
	);
	await page.route('**/memory/conversations', (route) => {
		if (route.request().method() === 'GET') {
			return route.fulfill({
				status: 200,
				contentType: 'application/json',
				body: JSON.stringify({ items: [], count: 0 })
			});
		}
		return route.continue();
	});
	await page.route('**/memory/settings', (route) =>
		route.fulfill({
			status: 200,
			contentType: 'application/json',
			body: JSON.stringify({
				id: 'settings_1',
				theme: 'system',
				accent_color: 'coral',
				custom_instructions: '',
				nickname: '',
				occupation: '',
				about_you: '',
				web_search: true,
				browser: true,
				shell_commands: true,
				complex_reasoning: true,
				computer_use: true,
				notification_email: true,
				notification_push: true,
				notification_marketing: false,
				data_share_analytics: true,
				data_share_training: false,
				backend_url: ''
			})
		})
	);
}

async function setupAuthenticated(page: Page): Promise<void> {
	await mockCommonRoutes(page);

	await page.route('**/workspace/users/me/**', (route) =>
		route.fulfill({
			status: 200,
			contentType: 'application/json',
			body: JSON.stringify(MOCK_USER)
		})
	);
	await page.route('**/workspace/users/me/', (route) =>
		route.fulfill({
			status: 200,
			contentType: 'application/json',
			body: JSON.stringify(MOCK_USER)
		})
	);

	await page.addInitScript((token) => {
		sessionStorage.setItem('midsphere-auth-token', token);
		localStorage.setItem(
			'midsphere-cookie-consent',
			JSON.stringify({ essential: true, analytics: false, errorTracking: false })
		);
	}, MOCK_TOKEN);
}

test('home page shows prompt input for authenticated user', async ({ page }) => {
	await setupAuthenticated(page);
	await page.goto('/');
	await page.waitForLoadState('networkidle');

	// Authenticated home page shows the main heading
	await expect(
		page.getByRole('main').getByRole('heading', { name: 'What can I do for you?' })
	).toBeVisible({ timeout: 10000 });
});

test('home page shows quick action chips', async ({ page }) => {
	await setupAuthenticated(page);
	await page.goto('/');
	await page.waitForLoadState('networkidle');

	// Quick action chips should be visible
	await expect(page.getByText('Create slides')).toBeVisible({ timeout: 10000 });
	await expect(page.getByText('Build websites')).toBeVisible();
});

test('unauthenticated home page shows landing page', async ({ page }) => {
	await mockCommonRoutes(page);
	await page.goto('/');
	await page.waitForLoadState('networkidle');

	// Landing page should be shown for unauthenticated users
	await expect(page.getByRole('heading', { name: /Think fast/ })).toBeVisible({ timeout: 10000 });
});
