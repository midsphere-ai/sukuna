export const openPanelTabs = writable<PanelTab[]>(['preview']);
export const activePanelTab = writable<PanelTab>('preview');
export const newTabPageActive = writable<boolean>(false);

export function addPanelTab(id: PanelTab): void {
	openPanelTabs.update((tabs) => {
		if (!tabs.includes(id)) return [...tabs, id];
		return tabs;
	});
	activePanelTab.set(id);
	newTabPageActive.set(false);
}

export function jumpToPanelTab(id: PanelTab): void {
	activePanelTab.set(id);
	newTabPageActive.set(false);
}

export function closePanelTabById(id: PanelTab): void {
	const tabs = get(openPanelTabs);
	const current = get(activePanelTab);
	const newTabs = tabs.filter((t) => t !== id);
	openPanelTabs.set(newTabs);

	if (current === id) {
		if (newTabs.length > 0) {
			activePanelTab.set(newTabs[0]);
		} else {
			newTabPageActive.set(true);
		}
	}
}

export function openNewTabPage(): void {
	newTabPageActive.set(true);
}

export function closeNewTabPage(): void {
	const tabs = get(openPanelTabs);
	if (tabs.length > 0) {
		newTabPageActive.set(false);
		activePanelTab.set(tabs[tabs.length - 1]);
	}
}
